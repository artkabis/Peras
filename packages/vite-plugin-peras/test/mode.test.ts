import { describe, expect, it } from "vitest";
import peras, {
  EXPORTS_MARKER,
  IMPORTS_MARKER,
  LOAD_MARKER,
  firstError,
  moduleCode,
  modeOf,
  splitLoader,
} from "../src/index.ts";

describe("modeOf", () => {
  it("reads the mode from the extension", () => {
    expect(modeOf("/src/dsp.peras")).toBe("owned");
    expect(modeOf("/src/ui.apeiron")).toBe("managed");
  });

  it("ignores Vite query strings", () => {
    expect(modeOf("/src/dsp.peras?import")).toBe("owned");
  });

  it("returns null for other files", () => {
    expect(modeOf("/src/main.ts")).toBeNull();
    expect(modeOf("/src/peras.json")).toBeNull();
  });
});

describe("plugin", () => {
  it("is named and runs before other plugins", () => {
    const plugin = peras();
    expect(plugin.name).toBe("vite-plugin-peras");
    expect(plugin.enforce).toBe("pre");
  });
});

describe("firstError", () => {
  it("places the primary label of the first diagnostic", () => {
    const report = {
      errorCount: 2,
      files: [
        {
          path: "/src/a.peras",
          diagnostics: [
            {
              code: "E0101",
              message: { text: "missing `;`" },
              labels: [
                { primary: false, range: { start: { line: 1, column: 1 } } },
                { primary: true, range: { start: { line: 2, column: 12 } } },
              ],
            },
          ],
        },
      ],
    };
    expect(firstError(report)).toEqual({
      summary: "E0101: missing `;`",
      loc: { file: "/src/a.peras", line: 2, column: 12 },
    });
  });

  it("still says something without a diagnostic", () => {
    expect(firstError({ errorCount: 1, files: [] })).toEqual({
      summary: "1 error(s)",
      loc: undefined,
    });
  });
});

describe("moduleCode", () => {
  const compiled = {
    wasm: new Uint8Array([0, 0x61, 0x73, 0x6d, 1, 0, 0, 0]),
    imports: `${IMPORTS_MARKER}\nconst $imports = { peras_rt: {} };\n`,
    exports: `${EXPORTS_MARKER}\nconst $wasm = $instance.exports;\nexport const f = $wasm.f;\n`,
    dts: "",
    inputs: [],
  };

  it("inlines the module for the dev server", () => {
    const code = moduleCode(compiled);
    expect(code).toContain('atob("AGFzbQEAAAA=")');
    // The imports come first, and the module is instantiated with them.
    expect(code.startsWith(IMPORTS_MARKER)).toBe(true);
    expect(code).toContain("await WebAssembly.instantiate($bytes, $imports)");
    expect(code).toContain("export const f = $wasm.f;");
  });

  it("fetches the emitted asset in a build, streaming when the server allows it", () => {
    const code = moduleCode(compiled, "import.meta.ROLLUP_FILE_URL_x");
    expect(code).toContain("await fetch(import.meta.ROLLUP_FILE_URL_x)");
    expect(code).toContain("WebAssembly.instantiateStreaming($response, $imports)");
    expect(code).not.toContain("atob");
  });
});

describe("splitLoader", () => {
  const loader = [
    "// Generated by perasc.",
    IMPORTS_MARKER,
    "const $imports = {};",
    LOAD_MARKER,
    "const { instance: $instance } = await WebAssembly.instantiate($bytes, $imports);",
    EXPORTS_MARKER,
    "export const f = $instance.exports.f;",
    "",
  ].join("\n");

  it("keeps the imports and the exports, not the loading", () => {
    const { imports, exports } = splitLoader(loader);
    expect(imports).toBe(`${IMPORTS_MARKER}\nconst $imports = {};\n`);
    expect(exports).toBe(`${EXPORTS_MARKER}\nexport const f = $instance.exports.f;\n`);
  });

  it("refuses a loader without its markers", () => {
    expect(() => splitLoader(loader.replace(LOAD_MARKER, ""))).toThrow("does not understand");
  });
});
