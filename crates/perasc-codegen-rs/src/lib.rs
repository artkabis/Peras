//! Rust code generation for owned Peras modules (`.peras`).
//!
//! Emits a Rust crate without `unsafe`, built by `cargo` for
//! `wasm32-unknown-unknown`, then by `wasm-bindgen`. Semantics match the direct
//! WebAssembly backend exactly: integer arithmetic is written `wrapping_*` so that
//! it never depends on the build profile, and `as` saturates float-to-integer
//! conversions as `trunc_sat` does. Every Peras name gets a prefix (`p_` for
//! functions, `v<n>_` for variables), so no Peras name can clash with a Rust keyword.

use std::fmt::Write as _;

use perasc_ir::{BinOp, Const, Expr, ExprKind, Function, MathOp, Module, Stmt, Ty, UnOp};

/// The `wasm-bindgen` version the generated crate depends on; the
/// `wasm-bindgen` command-line tool must have exactly the same version.
pub const WASM_BINDGEN_VERSION: &str = "0.2.130";

/// The Rust toolchain the generated crate is built with, as in `rust-toolchain.toml`.
pub const RUST_TOOLCHAIN: &str = "1.99.1";

/// The files of a generated crate: `(relative path, contents)`.
#[must_use]
pub fn crate_files(module: &Module, name: &str) -> Vec<(String, String)> {
    let manifest = format!(
        "# Generated by perasc. Do not edit.\n\
         [package]\nname = \"{name}\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n\
         [lib]\ncrate-type = [\"cdylib\"]\n\n\
         [dependencies]\nwasm-bindgen = \"={WASM_BINDGEN_VERSION}\"\n\n\
         [profile.release]\nopt-level = 3\nlto = true\ncodegen-units = 1\n\n\
         [workspace]\n"
    );
    let toolchain = format!(
        "# Generated by perasc.\n[toolchain]\nchannel = \"{RUST_TOOLCHAIN}\"\n\
         targets = [\"wasm32-unknown-unknown\"]\nprofile = \"minimal\"\n"
    );
    vec![
        ("Cargo.toml".to_owned(), manifest),
        ("rust-toolchain.toml".to_owned(), toolchain),
        ("src/lib.rs".to_owned(), source(module)),
    ]
}

/// The Rust source of a module.
#[must_use]
pub fn source(module: &Module) -> String {
    let mut out = String::from(
        "// Generated by perasc. Do not edit.\n\
         #![allow(unreachable_code, unused_assignments, unused_labels, unused_mut, unused_parens, unused_variables)]\n\
         #![allow(clippy::all)]\n\
         #![forbid(unsafe_code)]\n\n\
         use wasm_bindgen::prelude::*;\n",
    );
    for function in &module.functions {
        out.push('\n');
        Emitter::function(&mut out, module, function);
    }
    out
}

const fn rust_type(ty: Ty) -> &'static str {
    match ty {
        Ty::I32 => "i32",
        Ty::I64 => "i64",
        Ty::F32 => "f32",
        Ty::F64 => "f64",
        Ty::Bool => "bool",
        Ty::Void => "()",
    }
}

struct Emitter<'a> {
    module: &'a Module,
    function: &'a Function,
    /// Next loop label number.
    labels: usize,
    /// Labels of the enclosing loops: `('l<n>, 'c<n>)`.
    loops: Vec<usize>,
    /// Labels of the enclosing blocks: `'b<n>`.
    blocks: Vec<usize>,
}

impl<'a> Emitter<'a> {
    fn function(out: &mut String, module: &'a Module, function: &'a Function) {
        let mut emitter = Self {
            module,
            function,
            labels: 0,
            loops: Vec::new(),
            blocks: Vec::new(),
        };
        let params: Vec<String> = function
            .params()
            .enumerate()
            .map(|(i, p)| format!("mut {}: {}", emitter.var(i), rust_type(p.ty)))
            .collect();
        if function.exported {
            let _ = writeln!(out, "#[wasm_bindgen(js_name = \"{}\")]", function.name);
            out.push_str("pub ");
        }
        let ret = if function.ret == Ty::Void {
            String::new()
        } else {
            format!(" -> {}", rust_type(function.ret))
        };
        let _ = writeln!(out, "fn p_{}({}){ret} {{", function.name, params.join(", "));
        for (i, local) in function.locals.iter().enumerate().skip(params.len()) {
            let _ = writeln!(
                out,
                "    let mut {}: {} = {};",
                emitter.var(i),
                rust_type(local.ty),
                default_value(local.ty)
            );
        }
        emitter.stmts(out, &function.body, 1);
        if function.ret != Ty::Void {
            // The checker proved every path returns; rustc cannot always see it.
            out.push_str("    unreachable!()\n");
        }
        out.push_str("}\n");
    }

    /// The Rust name of a local: `v3_count`.
    fn var(&self, index: usize) -> String {
        let name = self
            .function
            .locals
            .get(index)
            .map_or("x", |l| l.name.as_str());
        format!("v{index}_{name}")
    }

    fn stmts(&mut self, out: &mut String, stmts: &[Stmt], level: usize) {
        for stmt in stmts {
            self.stmt(out, stmt, level);
        }
    }

    fn stmt(&mut self, out: &mut String, stmt: &Stmt, level: usize) {
        let pad = "    ".repeat(level);
        match stmt {
            Stmt::Set(local, value) => {
                let target = self.var(usize::try_from(local.0).unwrap_or(0));
                let value = self.expr(value);
                let _ = writeln!(out, "{pad}{target} = {value};");
            }
            Stmt::Expr(e) => {
                let value = self.expr(e);
                let _ = writeln!(out, "{pad}let _ = {value};");
            }
            Stmt::If {
                cond,
                then,
                otherwise,
            } => {
                let cond = self.expr(cond);
                let _ = writeln!(out, "{pad}if {cond} {{");
                self.stmts(out, then, level + 1);
                if otherwise.is_empty() {
                    let _ = writeln!(out, "{pad}}}");
                } else {
                    let _ = writeln!(out, "{pad}}} else {{");
                    self.stmts(out, otherwise, level + 1);
                    let _ = writeln!(out, "{pad}}}");
                }
            }
            Stmt::Loop { cond, body, step } => {
                let n = self.labels;
                self.labels += 1;
                let _ = writeln!(out, "{pad}'l{n}: loop {{");
                if let Some(cond) = cond {
                    let cond = self.expr(cond);
                    let _ = writeln!(out, "{pad}    if !{cond} {{ break 'l{n}; }}");
                }
                self.loops.push(n);
                let _ = writeln!(out, "{pad}    'c{n}: {{");
                self.stmts(out, body, level + 2);
                let _ = writeln!(out, "{pad}    }}");
                self.loops.pop();
                self.stmts(out, step, level + 1);
                let _ = writeln!(out, "{pad}}}");
            }
            Stmt::Block(body) => {
                let n = self.labels;
                self.labels += 1;
                let _ = writeln!(out, "{pad}'b{n}: {{");
                self.blocks.push(n);
                self.stmts(out, body, level + 1);
                self.blocks.pop();
                let _ = writeln!(out, "{pad}}}");
            }
            Stmt::Leave(depth) => {
                let n = usize::try_from(*depth)
                    .ok()
                    .and_then(|d| self.blocks.iter().rev().nth(d))
                    .copied()
                    .unwrap_or(0);
                let _ = writeln!(out, "{pad}break 'b{n};");
            }
            Stmt::Break => {
                let n = self.loops.last().copied().unwrap_or(0);
                let _ = writeln!(out, "{pad}break 'l{n};");
            }
            Stmt::Continue => {
                let n = self.loops.last().copied().unwrap_or(0);
                let _ = writeln!(out, "{pad}break 'c{n};");
            }
            Stmt::Return(None) => {
                let _ = writeln!(out, "{pad}return;");
            }
            Stmt::Return(Some(value)) => {
                let value = self.expr(value);
                let _ = writeln!(out, "{pad}return {value};");
            }
        }
    }

    /// An expression, fully parenthesized.
    fn expr(&self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::Const(c) => constant(*c, e.ty),
            ExprKind::Local(local) => self.var(usize::try_from(local.0).unwrap_or(0)),
            ExprKind::Unary(op, operand) => {
                let x = self.expr(operand);
                match op {
                    UnOp::Neg if e.ty.is_int() => format!("({x}).wrapping_neg()"),
                    UnOp::Neg => format!("(-{x})"),
                    UnOp::Not | UnOp::BitNot => format!("(!{x})"),
                }
            }
            ExprKind::Binary(op, lhs, rhs) => {
                let (a, b) = (self.expr(lhs), self.expr(rhs));
                binary(*op, lhs.ty, &a, &b)
            }
            ExprKind::Call(id, args) => {
                let name = usize::try_from(id.0)
                    .ok()
                    .and_then(|i| self.module.functions.get(i))
                    .map_or("missing", |f| f.name.as_str());
                let args: Vec<String> = args.iter().map(|a| self.expr(a)).collect();
                format!("p_{name}({})", args.join(", "))
            }
            ExprKind::Convert(operand) => {
                format!("({} as {})", self.expr(operand), rust_type(e.ty))
            }
            ExprKind::Math(op, operand) => {
                let x = self.expr(operand);
                match (op, operand.ty.is_int()) {
                    (MathOp::Abs, true) => format!("({x}).wrapping_abs()"),
                    (op, _) => format!("({x}).{}()", op.name()),
                }
            }
        }
    }
}

fn binary(op: BinOp, ty: Ty, a: &str, b: &str) -> String {
    let int = ty.is_int();
    match op {
        BinOp::Add if int => format!("{a}.wrapping_add({b})"),
        BinOp::Sub if int => format!("{a}.wrapping_sub({b})"),
        BinOp::Mul if int => format!("{a}.wrapping_mul({b})"),
        BinOp::Rem if int => format!("{a}.wrapping_rem({b})"),
        BinOp::Shl => format!("{a}.wrapping_shl({b} as u32)"),
        BinOp::Shr => format!("{a}.wrapping_shr({b} as u32)"),
        // Integer `/` traps on zero and on `MIN / -1`, as `i32.div_s` does.
        other => format!("({a} {} {b})", other.symbol()),
    }
}

fn constant(c: Const, ty: Ty) -> String {
    match (c, ty) {
        (Const::Int(v), Ty::I64) if v == i64::MIN => "i64::MIN".to_owned(),
        (Const::Int(v), Ty::I32) if v == i64::from(i32::MIN) => "i32::MIN".to_owned(),
        (Const::Int(v), _) => format!("({v}{})", rust_type(ty)),
        (Const::Float(v), _) => format!("({v:?}{})", rust_type(ty)),
        (Const::Bool(v), _) => v.to_string(),
    }
}

const fn default_value(ty: Ty) -> &'static str {
    match ty {
        Ty::F32 | Ty::F64 => "0.0",
        Ty::Bool => "false",
        Ty::Void => "()",
        _ => "0",
    }
}

