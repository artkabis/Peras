//! JavaScript code generation for managed Peras modules (`.apeiron`).
//!
//! A managed module compiles to one ES module, from its syntax tree and the
//! checker's analysis ([decision 0008]). Its values are JavaScript's, in the
//! shapes the loader of owned modules already gives: a structure is an
//! object, an enumeration `{ kind, values }`, an option a value or
//! `undefined`, a tuple an array. Numbers keep the meaning they have in an
//! owned module: an `i32` wraps, an `i64` is a `BigInt`, an `f32` is rounded
//! after each operation, and a division by zero throws.
//!
//! Generic functions are compiled once per instance, as for WebAssembly, so
//! that `a + b` wraps or not by the type it is given.
//!
//! [decision 0008]: ../../../docs/en/decisions/0008-managed-mode.md

use std::collections::{BTreeSet, HashMap};
use std::fmt::Write as _;

use perasc_check::ty::{FloatTy, FnId, IntTy, Ty};
use perasc_check::{Analysis, NameKind};
use perasc_diag::{Diagnostic, Fix, Label, Message, Span, codes};
use perasc_syntax::ast::{Ast, Block, FnDecl, ItemKind};

