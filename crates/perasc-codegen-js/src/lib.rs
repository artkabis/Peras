/// How the module is written.
#[derive(Debug, Clone)]
pub struct Options {
    /// Imports of `./x.peras` name `./x.js`, the loader `perasc build` writes
    /// next to it. Off for Vite, whose plugin compiles `.peras` imports itself.
    pub peras_imports_as_js: bool,
    /// The text of the `RangeError` an index out of bounds throws, with
    /// `{index}` and `{length}` in it: the one owned modules throw, in the
    /// language of the build.
    pub bounds: String,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            peras_imports_as_js: false,
            bounds: "index {index} is out of bounds: the length is {length}".to_owned(),
        }
    }
}

/// Compiles a checked managed module to JavaScript.
///
/// # Errors
///
/// One `E0900` diagnostic per construct this generator does not support yet,
/// sorted by position.
pub fn generate(
    ast: &Ast,
    analysis: &Analysis,
    options: &Options,
) -> Result<String, Vec<Diagnostic>> {
    let mut module = Module::new(ast, analysis);
    module.nested_options();
    let body = module.items();
    if !module.diagnostics.is_empty() {
        let mut diagnostics = module.diagnostics;
        diagnostics.sort_by_key(|d| d.primary_span().map(|s| s.start));
        return Err(diagnostics);
    }
    let mut out = String::from("// Generated by perasc from a managed module.\n");
    for item in &ast.items {
        if let ItemKind::Import(decl) = &item.kind {
            let names: Vec<&str> = decl.names.iter().map(|n| ast.name(n.symbol)).collect();
            let from = if options.peras_imports_as_js {
                decl.from
                    .strip_suffix(".peras")
                    .map_or_else(|| decl.from.clone(), |stem| format!("{stem}.js"))
            } else {
                decl.from.clone()
            };
            let _ = writeln!(
                out,
                "import {{ {} }} from {};",
                names.join(", "),
                expr::string_literal(&from)
            );
        }
    }
    for helper in runtime::closure(&module.helpers) {
        out.push_str(&runtime::source(helper, &options.bounds));
        out.push('\n');
    }
    out.push_str(&body);
    Ok(out)
}

/// The whole module being generated.
struct Module<'a> {
    ast: &'a Ast,
    analysis: &'a Analysis,
    /// The runtime helpers the code calls.
    helpers: BTreeSet<&'static str>,
    diagnostics: Vec<Diagnostic>,
    /// The JavaScript name of each function that is not generic, by its id.
    fns: HashMap<usize, String>,
    /// The JavaScript name of each instance of a generic function.
    instances: HashMap<(usize, Vec<Ty>), String>,
    /// The binding each declared name has, by its span.
    declared: HashMap<(u32, u32), usize>,
    /// The names given at the module's level.
    top: HashMap<usize, String>,
    /// The function being generated.
    current: Function,
}

/// What generating one function needs.
#[derive(Default)]
struct Function {
    /// Its type arguments, when it is an instance of a generic one.
    args: Vec<Ty>,
    /// The JavaScript name of each local binding.
    locals: HashMap<usize, String>,
    /// How many times each name was given, to make the next one unique.
    taken: HashMap<String, u32>,
    /// Temporaries made so far.
    temps: u32,
    /// The statements written so far, at the current depth.
    lines: Vec<String>,
    /// The current depth of blocks, for indentation.
    depth: usize,
    /// Inside an arrow function: `?` cannot return from the function.
    in_lambda: bool,
    /// The bounds proven by the loops being generated.
    proofs: Vec<bounds::Proof>,
}

