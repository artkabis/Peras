/// `name`, or `name$` when JavaScript reserves it.
fn safe(name: &str) -> String {
    if RESERVED.contains(&name) {
        format!("{name}$")
    } else {
        name.to_owned()
    }
}

impl<'a> Module<'a> {
    fn new(ast: &'a Ast, analysis: &'a Analysis) -> Self {
        let declared = analysis
            .bindings
            .iter()
            .enumerate()
            .filter_map(|(i, b)| b.span.map(|s| ((s.start, s.end), i)))
            .collect();
        Self {
            ast,
            analysis,
            helpers: BTreeSet::new(),
            diagnostics: Vec::new(),
            fns: HashMap::new(),
            instances: HashMap::new(),
            declared,
            top: HashMap::new(),
            current: Function::default(),
        }
    }

    /// Every function, instance and module variable, in the source's order.
    fn items(&mut self) -> String {
        let decls = self.ast.functions();
        // Names first: a function may call one declared after it.
        let mut taken: HashMap<String, u32> = HashMap::new();
        let mut unique = |base: String| {
            let n = taken.entry(base.clone()).or_insert(0);
            *n += 1;
            if *n == 1 { base } else { format!("{base}${n}") }
        };
        for (index, decl) in decls.iter().enumerate() {
            let name = self.ast.name(decl.name.symbol);
            let base = match decl.impl_of {
                Some(of) => format!("{}${name}", self.ast.name(of.symbol)),
                None => safe(name),
            };
            if !self.analysis.is_generic(FnId(index)) {
                self.fns.insert(index, unique(base));
            }
        }
        for (k, (id, args)) in self.analysis.instances.iter().enumerate() {
            if let Some(decl) = decls.get(id.0) {
                let name = self.ast.name(decl.name.symbol);
                let base = match decl.impl_of {
                    Some(of) => format!("{}${name}", self.ast.name(of.symbol)),
                    None => safe(name),
                };
                self.instances
                    .insert((id.0, args.clone()), unique(format!("{base}${k}")));
            }
        }
        // Imported functions come after the module's own, by the checker.
        for (index, bound) in self.analysis.bindings.iter().enumerate() {
            match bound.kind {
                NameKind::Fn(id) if id.0 >= decls.len() => {
                    self.fns.insert(id.0, bound.name.clone());
                }
                NameKind::Global => {
                    self.top.insert(index, unique(safe(&bound.name)));
                }
                _ => {}
            }
        }
        let mut out = String::new();
        for item in &self.ast.items {
            match &item.kind {
                ItemKind::Global(local) => {
                    self.current = Function::default();
                    let value = local.init.map(|init| self.expr(init));
                    let name = self.binding_name(local.name.span);
                    let keyword = if local.mutable { "let" } else { "const" };
                    for line in std::mem::take(&mut self.current.lines) {
                        out.push_str(&line);
                        out.push('\n');
                    }
                    match value {
                        Some(value) => {
                            let _ = writeln!(out, "{keyword} {name} = {value};");
                        }
                        None => {
                            let _ = writeln!(out, "let {name};");
                        }
                    }
                }
                ItemKind::Fn(decl) => self.function_and_instances(&decls, decl, &mut out),
                ItemKind::Impl(decl) => {
                    for method in &decl.methods {
                        self.function_and_instances(&decls, method, &mut out);
                    }
                }
                _ => {}
            }
        }
        out
    }

    /// A function, or each instance of a generic one.
    fn function_and_instances(&mut self, decls: &[&FnDecl], decl: &FnDecl, out: &mut String) {
        let Some(index) = decls.iter().position(|d| std::ptr::eq(*d, decl)) else {
            return;
        };
        if let Some(name) = self.fns.get(&index).cloned() {
            self.function(decl, &name, Vec::new(), out);
        }
        let instances: Vec<(Vec<Ty>, String)> = self
            .analysis
            .instances
            .iter()
            .filter(|(id, _)| id.0 == index)
            .filter_map(|(id, args)| {
                let name = self.instances.get(&(id.0, args.clone()))?;
                Some((args.clone(), name.clone()))
            })
            .collect();
        for (args, name) in instances {
            self.function(decl, &name, args, out);
        }
    }

    fn function(&mut self, decl: &FnDecl, name: &str, args: Vec<Ty>, out: &mut String) {
        self.current = Function {
            args,
            depth: 1,
            ..Function::default()
        };
        let params: Vec<String> = decl
            .params
            .iter()
            .map(|p| self.declare(p.name.span, self.ast.name(p.name.symbol)))
            .collect();
        self.block_stmts(&decl.body);
        let export = if decl.exported && decl.impl_of.is_none() {
            "export "
        } else {
            ""
        };
        let asynchronous = if decl.is_async { "async " } else { "" };
        let _ = writeln!(
            out,
            "{export}{asynchronous}function {name}({}) {{",
            params.join(", ")
        );
        for line in std::mem::take(&mut self.current.lines) {
            out.push_str(&line);
            out.push('\n');
        }
        out.push_str("}\n");
    }

    /// The statements of a block, at the current depth.
    fn block_stmts(&mut self, block: &Block) {
        for stmt in &block.stmts {
            self.stmt(stmt);
        }
    }

    // --- Names ------------------------------------------------------------

    /// Gives a new local, declared at `span`, a name unique in its function.
    fn declare(&mut self, span: Span, text: &str) -> String {
        let base = safe(text);
        let n = self.current.taken.entry(base.clone()).or_insert(0);
        *n += 1;
        let name = if *n == 1 { base } else { format!("{base}${n}") };
        if let Some(&binding) = self.declared.get(&(span.start, span.end)) {
            self.current.locals.insert(binding, name.clone());
        }
        name
    }

    /// The name of the binding declared at `span`: a module variable's.
    fn binding_name(&self, span: Span) -> String {
        self.declared
            .get(&(span.start, span.end))
            .and_then(|b| self.top.get(b))
            .cloned()
            .unwrap_or_else(|| "$unnamed".to_owned())
    }

    /// The binding a name read refers to.
    fn bound(&self, id: perasc_syntax::ast::ExprId) -> Option<(usize, NameKind)> {
        let &index = self.analysis.names.get(&id)?;
        Some((index, self.analysis.bindings.get(index)?.kind))
    }

    /// The JavaScript name of a variable.
    fn variable(&self, binding: usize) -> String {
        self.current
            .locals
            .get(&binding)
            .or_else(|| self.top.get(&binding))
            .cloned()
            .unwrap_or_else(|| "$unnamed".to_owned())
    }

    /// A new temporary.
    fn temp(&mut self) -> String {
        self.current.temps += 1;
        format!("$t{}", self.current.temps)
    }

    /// Writes a statement at the current depth.
    fn line(&mut self, text: impl AsRef<str>) {
        let indent = "  ".repeat(self.current.depth);
        self.current
            .lines
            .push(format!("{indent}{}", text.as_ref()));
    }

    /// Runs `f` with its statements written apart, one level deeper; gives
    /// its result and the statements.
    fn apart<T>(&mut self, f: impl FnOnce(&mut Self) -> T) -> (T, Vec<String>) {
        let saved = std::mem::take(&mut self.current.lines);
        self.current.depth += 1;
        let value = f(self);
        self.current.depth -= 1;
        let lines = std::mem::replace(&mut self.current.lines, saved);
        (value, lines)
    }

    /// Calls a runtime helper, which the module then carries.
    fn helper(&mut self, name: &'static str) -> &'static str {
        self.helpers.insert(name);
        name
    }

    // --- Types ------------------------------------------------------------

    /// The type of an expression, in the instance being generated.
    fn ty(&self, id: perasc_syntax::ast::ExprId) -> Ty {
        self.analysis.types.get(&id).map_or(Ty::Error, |t| {
            self.analysis.subst(t, &self.current.args).defaulted()
        })
    }

    /// The fields of a structure, in order.
    fn fields(&self, ty: &Ty) -> Vec<String> {
        match ty {
            Ty::Struct(id, _) => self
                .analysis
                .structs
                .get(id.0)
                .map(|(_, fields)| fields.iter().map(|(n, _)| n.clone()).collect())
                .unwrap_or_default(),
            _ => Vec::new(),
        }
    }

    /// Whether a structure is a tuple: an array in JavaScript.
    fn is_tuple(&self, ty: &Ty) -> bool {
        self.fields(ty).first().is_some_and(|f| f == "0")
    }

    /// Reports each expression whose type holds an option of an option: in
    /// JavaScript, `Some(None)` and `None` are both `undefined`.
    fn nested_options(&mut self) {
        fn nested(ty: &Ty) -> bool {
            match ty {
                Ty::Option(inner) => matches!(**inner, Ty::Option(_)) || nested(inner),
                Ty::Array(t) | Ty::Set(t) | Ty::Promise(t) => nested(t),
                Ty::Map(a, b) | Ty::Result(a, b) => nested(a) || nested(b),
                _ => false,
            }
        }
        let mut found: Vec<Span> = self
            .analysis
            .types
            .iter()
            .filter(|(_, ty)| nested(ty))
            .map(|(id, _)| self.ast.expr(*id).span)
            .collect();
        found.sort_by_key(|s| (s.start, s.end));
        if let Some(&first) = found.first() {
            self.unsupported(first, "nested-option");
        }
    }

    /// Reports a construct this generator does not support yet.
    fn unsupported(&mut self, span: Span, feature: &'static str) {
        self.diagnostics.push(Diagnostic {
            code: codes::NOT_SUPPORTED_YET,
            message: Message::new("gen-unsupported").text("feature", feature),
            labels: vec![Label {
                span,
                message: Message::new("gen-unsupported-label").text("feature", feature),
                primary: true,
            }],
            cause: Message::new("gen-unsupported-why"),
            fix: Fix {
                message: Message::new("gen-unsupported-fix"),
                edits: Vec::new(),
            },
        });
    }
}

/// How an integer type wraps a JavaScript value of the right kind.
fn wrap(int: IntTy, value: &str) -> String {
    match int {
        IntTy::I32 => format!("(({value}) | 0)"),
        IntTy::U32 => format!("(({value}) >>> 0)"),
        IntTy::I16 => format!("((({value}) << 16) >> 16)"),
        IntTy::I8 => format!("((({value}) << 24) >> 24)"),
        IntTy::U16 => format!("(({value}) & 65535)"),
        IntTy::U8 => format!("(({value}) & 255)"),
        IntTy::I64 => format!("BigInt.asIntN(64, {value})"),
        IntTy::U64 => format!("BigInt.asUintN(64, {value})"),
    }
}

/// Whether an integer type is a `BigInt` in JavaScript.
const fn is_big(int: IntTy) -> bool {
    matches!(int, IntTy::I64 | IntTy::U64)
}

/// The smallest and largest values of an integer type that is a number.
const fn range(int: IntTy) -> (i64, i64) {
    match int {
        IntTy::I8 => (-128, 127),
        IntTy::I16 => (-32_768, 32_767),
        IntTy::U8 => (0, 255),
        IntTy::U16 => (0, 65_535),
        IntTy::U32 => (0, 4_294_967_295),
        IntTy::I32 | IntTy::I64 | IntTy::U64 => (-2_147_483_648, 2_147_483_647),
    }
}

/// Rounds to `f32` when the type is one.
fn round(ty: &Ty, value: String) -> String {
    if *ty == Ty::Float(FloatTy::F32) {
        format!("Math.fround({value})")
    } else {
        value
    }
}

