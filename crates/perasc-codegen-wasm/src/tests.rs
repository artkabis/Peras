use super::{EXPORTS_MARKER, IMPORTS_MARKER, LOAD_MARKER, compile, dts, js_loader};

fn module(source: &str) -> perasc_ir::Module {
    let parsed = perasc_syntax::parse(source);
    assert_eq!(parsed.diagnostics, []);
    let analysis = perasc_check::analyze(&parsed.ast, source);
    assert_eq!(analysis.diagnostics, []);
    perasc_ir::lower(&parsed.ast, &analysis).unwrap_or_else(|e| unreachable!("{e:?}"))
}

const KERNELS: &str = include_str!("../../../bench/backends/kernels.peras");

const EVERY_CONSTRUCT: &str = "export fn all(a: i32, b: i64, x: f32, y: f64, ok: bool): f64 {
  let i = -a % 3 / 2 & 7 | 1 ^ 2;
  let j = (b << 2) >> 1;
  let k = ~a;
  let z = -x * 2.0 / 3.0 + (x - 1.0);
  if (!ok || a < 0 && b >= 0 || x != 0.0 || y == 1.0) { i = i.abs(); }
  for (;;) { if (i > 10) break; i++; continue; }
  while (j < 100) j += 1;
  let w = i.toF64() + j.toF64() + k.toF64() + z.toF64() + x.toF64().sqrt() + y.floor() + y.ceil() + b.abs().toF64();
  w += a.wrappingAdd(1).toF64() + j.toI32().toF32().toF64() + y.toF32().toI64().toF64();
  return w;
}
";

#[test]
fn every_generated_module_is_valid_webassembly() {
    for source in [KERNELS, EVERY_CONSTRUCT] {
        let plain = module(source);
        let mut optimized = plain.clone();
        perasc_ir::optimize(&mut optimized);
        // The optimized kernels hold the `block` / `leave` of the unrolled `fib`.
        for ir in [plain, optimized] {
            let wasm = compile(&ir);
            let validated = wasmparser::Validator::new().validate_all(&wasm);
            assert!(validated.is_ok(), "{:?}\n{ir}", validated.err());
        }
    }
}

#[test]
fn only_exported_functions_are_exported() {
    let wasm = compile(&module(
        "export fn a(): i32 { return b(); }\nfn b(): i32 { return 1; }",
    ));
    let mut exports = Vec::new();
    for payload in wasmparser::Parser::new(0).parse_all(&wasm).flatten() {
        if let wasmparser::Payload::ExportSection(section) = payload {
            exports.extend(section.into_iter().flatten().map(|e| e.name.to_owned()));
        }
    }
    assert_eq!(exports, ["a"]);
}

#[test]
fn declarations_and_loader_follow_the_types() {
    let m = module(
        "export fn f(n: i64, x: f64, ok: bool): bool { return ok && n > 0 && x > 0.0; }\nfn hidden(): void {}",
    );
    assert_eq!(
        dts(&m),
        "// Generated by perasc.\nexport declare function f(n: bigint, x: number, ok: boolean): boolean;\n"
    );
    let js = js_loader(&m, "m.wasm", None);
    assert!(
        js.contains("export const f = (...args) => $wasm.f(...args) !== 0;"),
        "{js}"
    );
    assert!(!js.contains("hidden"), "{js}");
    // vite-plugin-peras splits the loader on this exact line (`EXPORTS_MARKER` in
    // its source): changing it here means changing it there.
    assert_eq!(EXPORTS_MARKER, "// perasc:exports (needs `$instance`)");
    assert_eq!(IMPORTS_MARKER, "// perasc:imports");
    assert_eq!(LOAD_MARKER, "// perasc:load (needs `$imports`)");
    let imports = js.find(IMPORTS_MARKER).unwrap_or(usize::MAX);
    let load = js.find(LOAD_MARKER).unwrap_or(0);
    let exports = js.find(EXPORTS_MARKER).unwrap_or(0);
    assert!(imports < load && load < exports, "{js}");
    let (_, exports) = js.split_once(EXPORTS_MARKER).unwrap_or_default();
    assert!(
        exports
            .trim_start()
            .starts_with("const $wasm = $instance.exports;"),
        "{js}"
    );
}

#[test]
fn structures_cross_into_javascript_as_objects() {
    let source = "export struct V { x: f64; y: f64; }\nexport struct S { a: V; ok: bool; }\n\
                  export fn flip(s: S): S { return S(V(s.a.y, s.a.x), !s.ok); }\n\
                  export fn len(v: V): f64 { return v.x + v.y; }\n";
    let m = module(source);
    let wasm = compile(&m);
    let validated = wasmparser::Validator::new().validate_all(&wasm);
    assert!(validated.is_ok(), "{:?}", validated.err());
    let js = js_loader(&m, "m.wasm", None);
    assert!(
        js.contains("export const flip = (s) => { const $r = $wasm.flip(s.a.x, s.a.y, s.ok); return ({ a: ({ x: $r[0], y: $r[1] }), ok: $r[2] !== 0 }); };"),
        "{js}"
    );
    assert!(
        js.contains("export const len = (v) => { const $r = $wasm.len(v.x, v.y); return $r; };"),
        "{js}"
    );
    let types = dts(&m);
    assert!(
        types.contains("export interface V { x: number; y: number; }"),
        "{types}"
    );
    assert!(
        types.contains("export interface S { a: V; ok: boolean; }"),
        "{types}"
    );
    assert!(
        types.contains("export declare function flip(s: S): S;"),
        "{types}"
    );
    // Each interface once, a nested one first.
    assert_eq!(types.matches("export interface V ").count(), 1, "{types}");
    assert!(
        types.find("interface V ") < types.find("interface S "),
        "{types}"
    );
}
