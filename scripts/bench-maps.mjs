// Maps and sets benchmark: bench/maps/maps.peras, compiled with the TLSF
// allocator, against the same work on JavaScript's Map and Set, in Node
// (V8, the engine of Chrome). Each case is checked to give the same result
// first; then JavaScript and Peras alternate, medians of the runs after two
// of warm-up.
// Usage: node scripts/bench-maps.mjs [--check] [--perasc <path>]
//        --check: small inputs, one run: only checks the results agree.
// Writes bench/maps/RESULTS.md, unless --check.
import { spawnSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { cpus } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const check = process.argv.includes("--check");
const at = process.argv.indexOf("--perasc");
const root = join(import.meta.dirname, "..");
const perasc = at > 0 ? (process.argv[at + 1] ?? "") : join(root, "target", "release", "perasc");
const work = join(root, "target", "bench-maps");
rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });
const args = [
  "build",
  join(root, "bench", "maps", "maps.peras"),
  "--allocator",
  "tlsf",
  "--out",
  work,
];
const built = spawnSync(perasc, args, { encoding: "utf8" });
if (built.status !== 0) throw new Error(`perasc ${args.join(" ")}\n${built.stdout}${built.stderr}`);

/** @typedef {{ countWords(t: string): number, integers(n: number): bigint, distinct(n: number): number, __perasHeap: { checkLeaks(): void } }} Peras */
/** @type {unknown} */
const loaded = await import(pathToFileURL(join(work, "maps.js")).href);
const peras = /** @type {Peras} */ (loaded);

const scale = check ? 0.01 : 1;
const words = ["the", "web", "été", "naïve", "compile", "rust", "wasm", "données", "a", "loop"];
let seed = 1;
const random = () => {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 4294967296;
};
const parts = [];
for (let i = 0; i < 1_000_000 * scale; i++)
  parts.push(`${words[Math.floor(random() * 10)] ?? ""}${String(Math.floor(random() * 5000))}`);
const text = parts.join(" ");
const n = Math.round(2_000_000 * scale);

// The same work in JavaScript, as one would write it: number keys.
const js = {
  /** @param {string} t */
  countWords(t) {
    /** @type {Map<string, number>} */
    const counts = new Map();
    for (const w of t.split(" ")) counts.set(w, (counts.get(w) ?? 0) + 1);
    return counts.size;
  },
  /** @param {number} count */
  integers(count) {
    /** @type {Map<number, number>} */
    const m = new Map();
    let s = 7;
    let total = 0;
    for (let i = 0; i < count; i++) {
      s = (Math.imul(s, 1103515245) + 12345) | 0;
      const k = Math.trunc(Math.trunc(s / 65536) % 50000);
      const op = Math.abs(Math.trunc(s / 7) % 4);
      if (op <= 1) m.set(k, i);
      else if (op === 2) total += m.get(k) ?? -1;
      else m.delete(k);
    }
    return BigInt(total + m.size);
  },
  /** @param {number} count */
  distinct(count) {
    const seen = new Set();
    let s = 3;
    for (let i = 0; i < count; i++) {
      s = (Math.imul(s, 1103515245) + 12345) | 0;
      seen.add(Math.trunc(s / 65536) % 200000);
    }
    return seen.size;
  },
};

/** @type {[string, (f: typeof js | typeof peras) => unknown][]} */
const cases = [
  [`count words, ${String(parts.length)} words, Map<String, i32>`, (f) => f.countWords(text)],
  [`integer keys, ${String(n)} operations, Map<i64, i64>`, (f) => f.integers(n)],
  [`distinct integers, ${String(n)} adds, Set<i32>`, (f) => f.distinct(n)],
];
/** @param {number[]} xs */
const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)] ?? 0;
const runs = check ? 1 : 15;
const lines = [];
for (const [name, run] of cases) {
  const [a, b] = [String(run(peras)), String(run(js))];
  if (a !== b) throw new Error(`${name}: Peras gives ${a}, JavaScript ${b}`);
  const times = { peras: /** @type {number[]} */ ([]), js: /** @type {number[]} */ ([]) };
  for (let r = 0; r < runs + (check ? 0 : 2); r++) {
    for (const [side, f] of /** @type {const} */ ([
      ["peras", peras],
      ["js", js],
    ])) {
      const t0 = performance.now();
      run(f);
      if (r >= 2 || check) times[side].push(performance.now() - t0);
    }
  }
  const [p, j] = [median(times.peras), median(times.js)];
  lines.push(`| ${name} | ${j.toFixed(1)} | ${p.toFixed(1)} | ${(j / p).toFixed(2)} |`);
}
peras.__perasHeap.checkLeaks();
if (check) {
  console.log("Maps and sets give what JavaScript's give, with no leak.");
} else {
  const report = [
    "# Maps and sets — results",
    "",
    "Generated by `node scripts/bench-maps.mjs`: [bench/maps/maps.peras](maps.peras) against the same work on JavaScript's `Map` and `Set`, with number keys, in Node.",
    "",
    `Machine: ${cpus()[0]?.model ?? "?"}, Node ${process.version}. Medians of ${String(runs)} runs after 2 of warm-up, Peras and JavaScript alternating. Speed-up: JavaScript's time divided by Peras's.`,
    "",
    "| Case | JavaScript (ms) | Peras (ms) | Speed-up |",
    "| --- | --: | --: | --: |",
    ...lines,
    "",
  ].join("\n");
  writeFileSync(join(root, "bench", "maps", "RESULTS.md"), report);
  console.log(report);
}
