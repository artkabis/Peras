// Web Workers benchmark: what splitting a kernel of bench/browser across
// workers brings, each worker with its own instance of the Peras module.
// Builds bench/browser/kernels.peras, serves it with bench/browser/workers.js
// (the page) and worker.js (a worker), and runs them in Chromium.
// Usage: node scripts/bench-workers.mjs           (needs a release perasc)
//        node scripts/bench-workers.mjs --check   small inputs, one run:
//        only checks that split results equal direct ones.
// PERAS_CHROMIUM names the Chromium to use, as for the other benchmarks.
// Writes bench/browser/WORKERS.md.
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { cpus } from "node:os";
import { extname, join } from "node:path";
import { chromium } from "playwright";

/** @typedef {import("../bench/browser/workers.js").Row} Row */

const check = process.argv.includes("--check");
const root = join(import.meta.dirname, "..");
const bench = join(root, "bench", "browser");
const work = join(root, "target", "bench-workers");
const perasc = join(root, "target", "release", "perasc");

rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });
const args = ["build", join(bench, "kernels.peras"), "--allocator", "tlsf", "--out", work];
const built = spawnSync(perasc, args, { encoding: "utf8" });
if (built.status !== 0) throw new Error(`perasc ${args.join(" ")}\n${built.stdout}${built.stderr}`);
for (const file of ["workers.js", "worker.js"]) copyFileSync(join(bench, file), join(work, file));
writeFileSync(
  join(work, "index.html"),
  "<!doctype html><meta charset=utf-8><title>workers</title>\n",
);

/** @type {Record<string, string>} */
const types = { ".html": "text/html", ".js": "text/javascript", ".wasm": "application/wasm" };
const server = createServer((request, response) => {
  const path = join(work, new URL(request.url ?? "/", "http://x").pathname);
  if (!path.startsWith(work)) {
    response.writeHead(403).end();
    return;
  }
  try {
    const body = readFileSync(path);
    response.writeHead(200, {
      "content-type": types[extname(path)] ?? "application/octet-stream",
    });
    response.end(body);
  } catch {
    response.writeHead(404).end();
  }
});
/** @type {string} */
const base = await new Promise((resolve) => {
  server.listen(0, "127.0.0.1", () => {
    const address = server.address();
    const port = typeof address === "object" && address !== null ? address.port : 0;
    resolve(`http://127.0.0.1:${String(port)}`);
  });
});

const executablePath = process.env.PERAS_CHROMIUM;
const browser = await chromium.launch(executablePath === undefined ? {} : { executablePath });
try {
  const page = await browser.newPage();
  await page.goto(`${base}/index.html`);
  const config = check ? { scale: 0.01, runs: 1 } : { scale: 1, runs: 15 };
  /** @type {{ cores: number, rows: Row[] }} */
  const measured = await page.evaluate(
    async ({ url, config }) => {
      /** @type {unknown} */
      const loaded = await import(url);
      const page = /** @type {typeof import("../bench/browser/workers.js")} */ (loaded);
      return page.measure(config);
    },
    { url: `${base}/workers.js`, config },
  );
  if (check) {
    console.log(
      `Split across workers, the kernels give what they give directly, in Chromium ${browser.version()}.`,
    );
  } else {
    /** @param {number} x */
    const ms = (x) => (x >= 10 ? x.toFixed(1) : x.toFixed(2));
    const lines = [
      "# Web Workers — results",
      "",
      "Generated by `node scripts/bench-workers.mjs`. What it measures and what the results say: [README](../README.md#web-workers).",
      "",
      `Machine: ${cpus()[0]?.model ?? "?"}, ${String(cpus().length)} cores (the page sees ${String(measured.cores)}). Chromium ${browser.version()}, headless. Medians of ${String(config.runs)} runs after 2 of warm-up, every way alternating.`,
      "",
      "_Direct_: the kernel called on the main thread, its arrays already in the module's memory: the work alone. _N workers_: the data split in N parts, transferred to N workers, each with its own instance of the module, copied into it and back, the parts gathered: everything counted. Speed-up: the direct time divided by this one.",
      "",
      "| Kernel | Way | Median (ms) | Speed-up |",
      "| --- | --- | --: | --: |",
    ];
    for (const kernel of [...new Set(measured.rows.map((r) => r.kernel))]) {
      const rows = measured.rows.filter((r) => r.kernel === kernel);
      const directTime = rows.find((r) => r.way === "direct")?.median ?? 0;
      rows.forEach((r, i) => {
        const way = r.way === "direct" ? "direct" : `${r.way} worker${r.way === "1" ? "" : "s"}`;
        lines.push(
          `| ${i === 0 ? kernel : ""} | ${way} | ${ms(r.median)} | ${(directTime / r.median).toFixed(2)} |`,
        );
      });
    }
    lines.push(
      "",
      "Every split result was checked equal to the direct one, element by element.",
      "",
    );
    writeFileSync(join(bench, "WORKERS.md"), lines.join("\n"));
    console.log(lines.join("\n"));
  }
} finally {
  await browser.close();
  server.close();
}
