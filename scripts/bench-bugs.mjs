// Bug-catching benchmark: each case in bench/bugs is a known bug written twice,
// in TypeScript and in Peras. The script asks three tools whether they reject it:
//   1. tsc with the strictest options (bench/bugs/tsconfig.json),
//   2. the same plus typescript-eslint's strict type-aware preset (bench/bugs/eslint.config.js),
//   3. perasc check.
// It writes bench/bugs/RESULTS.md and prints the totals.
// Usage: node scripts/bench-bugs.mjs   (needs `pnpm install` and a Rust toolchain)
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const dir = join(root, "bench", "bugs");

/** @typedef {{ id: string, category: string }} Case */
const casesJson = /** @type {unknown} */ (
  JSON.parse(readFileSync(join(dir, "cases.json"), "utf8"))
);
const cases = /** @type {Case[]} */ (casesJson);

/**
 * Runs a command and returns its standard output, whatever its exit code.
 * @param {string} command
 * @param {string[]} args
 * @returns {string}
 */
function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  return result.stdout;
}

// First error per file, for each tool.
/** @type {Map<string, string>} */
const tsc = new Map();
/** @type {Map<string, string>} */
const eslint = new Map();
/** @type {Map<string, string>} */
const peras = new Map();

// 1. tsc: one run over the whole corpus; lines look like `file.ts(3,7): error TS2322: …`.
const tscOutput = run("pnpm", [
  "exec",
  "tsc",
  "-p",
  "bench/bugs/tsconfig.json",
  "--pretty",
  "false",
]);
for (const line of tscOutput.split("\n")) {
  const match = /^bench\/bugs\/([\w-]+)\.ts\(\d+,\d+\): error (TS\d+): (.*)$/.exec(line);
  if (match?.[1] && match[2] && match[3] && !tsc.has(match[1])) {
    tsc.set(match[1], `${match[2]}: ${match[3]}`);
  }
}

// 2. ESLint with type information: JSON report, errors only.
const eslintOutput = run("pnpm", [
  "exec",
  "eslint",
  "--no-config-lookup",
  "-c",
  "bench/bugs/eslint.config.js",
  "-f",
  "json",
  ...cases.map((c) => `bench/bugs/${c.id}.ts`),
]);
/** @typedef {{ filePath: string, messages: { severity: number, ruleId: string | null, message: string }[] }} EslintFile */
const eslintJson = /** @type {unknown} */ (JSON.parse(eslintOutput || "[]"));
const eslintFiles = /** @type {EslintFile[]} */ (eslintJson);
for (const file of eslintFiles) {
  const id = file.filePath.split("/").pop()?.replace(/\.ts$/, "") ?? "";
  const first = file.messages.find((m) => m.severity === 2);
  if (first) eslint.set(id, `${first.ruleId ?? "parse"}: ${first.message}`);
}

// 3. perasc, built once, then asked for a JSON report.
run("cargo", ["build", "--quiet", "-p", "perasc"]);
const perascOutput = run(join(root, "target", "debug", "perasc"), [
  "check",
  ...cases.map((c) => `bench/bugs/${c.id}.peras`),
  "--json",
  "--lang",
  "en",
]);
/** @typedef {{ path: string, diagnostics: { code: string, message: { text: string } }[] }} PerasFile */
const perascJson = /** @type {unknown} */ (JSON.parse(perascOutput));
const report = /** @type {{ files: PerasFile[] }} */ (perascJson);
for (const file of report.files) {
  const id =
    file.path
      .split("/")
      .pop()
      ?.replace(/\.peras$/, "") ?? "";
  const first = file.diagnostics[0];
  if (first) peras.set(id, `${first.code}: ${first.message.text}`);
}

/**
 * A table cell: a mark, then the first error, shortened.
 * @param {Map<string, string>} results
 * @param {string} id
 * @returns {string}
 */
function cell(results, id) {
  const error = results.get(id);
  if (error === undefined) return "✗ accepted";
  const short = error.length > 70 ? `${error.slice(0, 69)}…` : error;
  return `✓ ${short.replaceAll("|", "\\|")}`;
}

/**
 * Number of cases of a category rejected by a tool.
 * @param {Map<string, string>} results
 * @param {string} category
 * @returns {number}
 */
function score(results, category) {
  return cases.filter((c) => c.category === category && results.has(c.id)).length;
}

const lines = [
  "# Bug-catching benchmark — results",
  "",
  "Generated by `node scripts/bench-bugs.mjs`. Each case is a known bug, or a rule of rigour,",
  "written in TypeScript (`.ts`) and in Peras (`.peras`). ✓ means the tool rejects the code;",
  "the first error is shown.",
  "",
  "| Case | tsc (strictest) | tsc + typescript-eslint (strict) | perasc |",
  "| --- | --- | --- | --- |",
];
for (const c of cases) {
  const both = new Map([...tsc, ...eslint]);
  const combined = tsc.has(c.id) ? tsc : both;
  lines.push(
    `| ${c.id} (${c.category}) | ${cell(tsc, c.id)} | ${cell(combined, c.id)} | ${cell(peras, c.id)} |`,
  );
}
const merged = new Map([...eslint, ...tsc]);
const total = (/** @type {string} */ category) =>
  cases.filter((c) => c.category === category).length;
lines.push(
  "",
  "| Category | tsc (strictest) | tsc + typescript-eslint (strict) | perasc |",
  "| --- | --- | --- | --- |",
);
for (const category of ["bug", "rigour"]) {
  lines.push(
    `| ${category} | ${String(score(tsc, category))} / ${String(total(category))} | ${String(score(merged, category))} / ${String(total(category))} | ${String(score(peras, category))} / ${String(total(category))} |`,
  );
}
lines.push("");
writeFileSync(join(dir, "RESULTS.md"), lines.join("\n"));
console.log(lines.slice(-5).join("\n"));
