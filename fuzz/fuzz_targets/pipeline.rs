//! The whole pipeline on any text: every diagnostic renders in English and French,
//! as text and as JSON; a source with no error compiles to a valid WebAssembly
//! module, and the IR verifier never finds a compiler bug. The same text, as a
//! managed module, is checked and compiled to JavaScript without a panic.
#![no_main]

use libfuzzer_sys::fuzz_target;
use perasc_diag::i18n::Localizer;
use perasc_diag::json;
use perasc_diag::messages::Language;
use perasc_diag::render::{RenderOptions, render};
use perasc_diag::source::SourceFile;
use perasc_driver::{Allocator, DirectOptions, ToolError, build_direct, build_managed, check};

fuzz_target!(|data: &[u8]| {
    let Ok(source) = std::str::from_utf8(data) else {
        return;
    };
    // As a managed module: errors, or JavaScript; never a panic.
    let english = Localizer::new(Language::English);
    match build_managed(
        std::path::Path::new("fuzz.apeiron"),
        source,
        true,
        true,
        &english,
    ) {
        Ok(output) => assert!(output.js.starts_with("// Generated by perasc")),
        Err(ToolError::Diagnostics(_)) => {}
        Err(other) => panic!("compiler bug: {other:?}\n{source}"),
    }
    let checked = check(source);
    let file = SourceFile::new("fuzz.peras", source);
    for language in Language::ALL {
        let localizer = Localizer::new(language);
        for d in &checked.diagnostics {
            let text = render(d, &file, &localizer, RenderOptions { color: false });
            assert!(text.ends_with('\n'), "{text}");
            let value = json::diagnostic(d, &file, &localizer);
            assert!(serde_json::to_string(&value).is_ok());
        }
    }
    if !checked.diagnostics.is_empty() {
        return;
    }
    // Without optimizations or SIMD on the debug allocator, with both on TLSF.
    for (optimize, allocator) in [(false, Allocator::Debug), (true, Allocator::Tlsf)] {
        match build_direct(
            source,
            "fuzz.wasm",
            DirectOptions {
                optimize,
                allocator,
                simd: optimize,
                // The optimized build also exports jobs and their dispatchers.
                threads: optimize,
            },
            &Localizer::new(Language::English),
        ) {
            Ok(output) => {
                let valid = wasmparser::Validator::new().validate_all(&output.wasm);
                assert!(valid.is_ok(), "invalid module: {:?}\n{source}", valid.err());
            }
            // Not supported by code generation yet (E0900): a normal outcome.
            Err(ToolError::Diagnostics(_)) => {}
            Err(other) => panic!("compiler bug: {other:?}\n{source}"),
        }
    }
});
