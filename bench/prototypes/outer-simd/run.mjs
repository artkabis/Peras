// The ceiling of vectorizing across the outer loop: Mandelbrot and n-body,
// one value at a time and two f64 lanes at a time (src/lib.rs, Rust with
// WebAssembly SIMD, as Peras could emit it), next to Peras as it compiles
// them today and to JavaScript, usual and expert. Checks every variant gives
// the same result, bit for bit, then times them alternating, in Chromium.
// Usage: node bench/prototypes/outer-simd/run.mjs   (needs a release perasc,
// rustup and wasm-bindgen 0.2.130). Writes RESULTS.md next to this file.
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { cpus } from "node:os";
import { extname, join } from "node:path";
import { chromium } from "playwright";

const here = import.meta.dirname;
const root = join(here, "..", "..", "..");
const work = join(root, "target", "outer-simd");
const sh = (command, args, options = {}) => {
  const r = spawnSync(command, args, { encoding: "utf8", ...options });
  if (r.status !== 0) throw new Error(`${command} ${args.join(" ")}\n${r.stdout}${r.stderr}`);
};
rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });
sh("cargo", ["build", "--release", "--locked", "--target", "wasm32-unknown-unknown", "-q"], {
  cwd: here,
  env: { ...process.env, RUSTFLAGS: "-C target-feature=+simd128" },
});
sh("wasm-bindgen", [
  join(here, "target", "wasm32-unknown-unknown", "release", "outer_simd.wasm"),
  "--target",
  "web",
  "--out-dir",
  work,
]);
sh(join(root, "target", "release", "perasc"), [
  "build",
  join(root, "bench", "browser", "kernels.peras"),
  "--allocator",
  "tlsf",
  "--out",
  work,
]);
copyFileSync(join(root, "bench", "browser", "reference.js"), join(work, "reference.js"));
writeFileSync(
  join(work, "index.html"),
  "<!doctype html><meta charset=utf-8><title>outer simd</title>\n",
);

const types = { ".html": "text/html", ".js": "text/javascript", ".wasm": "application/wasm" };
const server = createServer((request, response) => {
  const path = join(work, new URL(request.url ?? "/", "http://x").pathname);
  try {
    const body = readFileSync(path);
    response.writeHead(200, { "content-type": types[extname(path)] ?? "application/octet-stream" });
    response.end(body);
  } catch {
    response.writeHead(404).end();
  }
});
const base = await new Promise((resolve) => {
  server.listen(0, "127.0.0.1", () => resolve(`http://127.0.0.1:${server.address().port}`));
});
const browser = await chromium.launch(
  process.env.PERAS_CHROMIUM ? { executablePath: process.env.PERAS_CHROMIUM } : {},
);
try {
  const page = await browser.newPage();
  await page.goto(`${base}/index.html`);
  const rounds = await page.evaluate(async (base) => {
    const proto = await import(`${base}/outer_simd.js`);
    await proto.default();
    const peras = await import(`${base}/kernels.js`);
    const js = await import(`${base}/reference.js`);
    const size = 600;
    const [n, steps] = [1000, 5];
    const variants = {
      mandel: [
        ["JavaScript", () => js.mandel(size)],
        ["Peras today", () => peras.mandel(size)],
        ["one at a time (Rust, as Peras)", () => proto.mandel_scalar(size)],
        ["two lanes (Rust SIMD)", () => proto.mandel_simd(size)],
      ],
      nbody: [
        ["JavaScript", () => js.nbody(n, steps)],
        ["JavaScript, expert", () => js.nbodyExpert(n, steps)],
        ["Peras today", () => peras.nbody(n, steps)],
        ["one at a time (Rust, as Peras)", () => proto.nbody_scalar(n, steps)],
        ["two lanes (Rust SIMD)", () => proto.nbody_simd(n, steps)],
      ],
    };
    for (const [kernel, list] of Object.entries(variants)) {
      const results = list.map(([, f]) => f());
      if (!results.every((r) => Object.is(r, results[0])))
        throw new Error(`${kernel}: results differ: ${results.join(" / ")}`);
    }
    const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];
    const out = [];
    for (let round = 0; round < 3; round++) {
      const row = {};
      for (const [kernel, list] of Object.entries(variants)) {
        const times = list.map(() => []);
        for (let r = 0; r < 18; r++)
          list.forEach(([, f], k) => {
            const t0 = performance.now();
            f();
            if (r >= 3) times[k].push(performance.now() - t0);
          });
        row[kernel] = list.map(([label], k) => [label, median(times[k])]);
      }
      out.push(row);
    }
    return out;
  }, base);
  const lines = [
    "# Vectorizing across the outer loop — a ceiling",
    "",
    "Generated by `node bench/prototypes/outer-simd/run.mjs`. Why: [README](README.md).",
    "",
    `Machine: ${cpus()[0]?.model ?? "?"}, ${cpus().length} cores. Chromium ${browser.version()}, headless. Medians of 15 runs after 3 of warm-up, every variant alternating, in each of 3 rounds. Every variant gave the same result, bit for bit.`,
    "",
  ];
  for (const kernel of Object.keys(rounds[0])) {
    lines.push(
      `## ${kernel}`,
      "",
      "| Variant | Round 1 (ms) | Round 2 | Round 3 | Against Peras today |",
      "| --- | --: | --: | --: | --: |",
    );
    const labels = rounds[0][kernel].map(([label]) => label);
    labels.forEach((label, k) => {
      const ms = rounds.map((r) => r[kernel][k][1]);
      const today = rounds.map((r) => r[kernel].find(([l]) => l === "Peras today")[1]);
      const ratios = ms.map((m, i) => (today[i] / m).toFixed(2));
      lines.push(
        `| ${label} | ${ms.map((m) => m.toFixed(1)).join(" | ")} | ${ratios.join(", ")} |`,
      );
    });
    lines.push("");
  }
  writeFileSync(join(here, "RESULTS.md"), lines.join("\n"));
  console.log(lines.join("\n"));
} finally {
  await browser.close();
  server.close();
}
